-- =====================================================================
-- SWITCHBOARD RESULTS JOB
-- Reads replies from prepared.switchboard.biobank_responses and:
--   1. logs every reply in recontact (contact_type = 9 = Switchboard text)
--   2. schedules a collection for every "yes" (response = 1)
-- Safe to re-run: both steps skip rows they already inserted.
-- (Sending texts is a separate job: see switchboard_department_texting.sql, part 2.)
-- =====================================================================


-- ---------------------------------------------------------------------
-- 1. Log each reply in recontact
--    recontact has no CSN column, so the CSN is written at the start of notes
--    ("Switchboard CSN <csn>: ...") and that prefix is used to skip rows already logged.
--    EMPI comes from switchboard_text_attempts (the text we sent for that CSN).
-- ---------------------------------------------------------------------
INSERT INTO biobank_analytics.pmbb_saliva.recontact (
    empi_id,
    contact_type,
    inserted,
    notes,
    staff_member
)
SELECT
    CAST(t.EMPI AS BIGINT)  AS empi_id,
    9                       AS contact_type,
    current_timestamp()     AS inserted,
    concat('Switchboard CSN ', r.csn, ': response ', CAST(r.response AS STRING),
           ' (appointment ', date_format(r.appt_date, 'yyyy-MM-dd HH:mm'), ', dept ', r.dept_id, ')') AS notes,
    'switchboard'           AS staff_member
FROM (
    -- one reply per CSN; if a patient replied more than once, keep the "yes" if there is one
    SELECT csn, appt_date, dept_id, response
    FROM prepared.switchboard.biobank_responses
    WHERE response IS NOT NULL
    QUALIFY ROW_NUMBER() OVER (PARTITION BY csn ORDER BY CASE WHEN response = 1 THEN 0 ELSE 1 END) = 1
) r
JOIN (
    SELECT EncounterEpicCsn, MAX(EMPI) AS EMPI
    FROM biobank_analytics.pmbb_saliva.switchboard_text_attempts
    GROUP BY EncounterEpicCsn
) t ON t.EncounterEpicCsn = r.csn
WHERE NOT EXISTS (
    SELECT 1 FROM biobank_analytics.pmbb_saliva.recontact rc
    WHERE rc.contact_type = 9
      AND rc.notes LIKE concat('Switchboard CSN ', r.csn, ':%')
);


-- ---------------------------------------------------------------------
-- 2. Schedule a collection for every "yes" so it shows on /upcoming_collections
--    Skips CSNs already in scheduled_collection (from a previous run or scheduled by hand)
--    and patients who withdrew. collection_id is generated by the table.
-- ---------------------------------------------------------------------
INSERT INTO biobank_analytics.pmbb_saliva.scheduled_collection (
    appointment_id,
    EMPI,
    DepartmentEpicId,
    staff_member,
    created_at,
    location_name,
    appointment_date,
    appointment_time,
    patient_name
)
SELECT
    u.EncounterEpicCsn,
    u.EMPI,
    u.DepartmentEpicId,
    'switchboard'       AS staff_member,
    current_timestamp() AS created_at,
    u.Appointment_Location,
    u.AppointmentDate,
    u.AppointemntTime,
    u.Patient_name
FROM (
    SELECT DISTINCT csn
    FROM prepared.switchboard.biobank_responses
    WHERE response = 1
) r
JOIN biobank_analytics.pmbb_saliva.upcoming_appointments_for_saliva u
  ON CAST(u.EncounterEpicCsn AS STRING) = r.csn
WHERE NOT EXISTS (
          SELECT 1 FROM biobank_analytics.pmbb_saliva.scheduled_collection sc
          WHERE CAST(sc.appointment_id AS STRING) = r.csn
      )
  AND NOT EXISTS (
          SELECT 1 FROM biobank_analytics.pmbb_saliva.withdraw w
          WHERE w.empi = u.EMPI
      )
QUALIFY ROW_NUMBER() OVER (PARTITION BY u.EncounterEpicCsn ORDER BY u.AppointmentInstant) = 1;
